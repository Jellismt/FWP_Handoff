-- The book's prose sections (definitions, licensing, ~35 Laws & Rules statute
-- sections, youth/disability, drawing explainers, access, contacts). Structured
-- tables (refund, restitution, youth chart) live as GFM pipe tables INSIDE body_md:
-- one editor, one renderer, and the print exporter parses GFM tables into ICML
-- <Table> anyway — so they're machine-readable, not opaque prose.
-- Drawing "statistics" (pp.43-45, p.137) are DRAWING-category content, NOT numeric
-- tables — the printed example is explicitly disclaimed as non-factual. A future
-- numeric regs.draw_stat table (fed by FWP's drawing-results system) is out of scope.
-- ============================================================================

