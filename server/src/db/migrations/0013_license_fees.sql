-- Printed fee/availability charts pp.12-13. One product per printed chart row;
-- discounted variants (NR-native, youth-sponsored, college) are AUDIENCE PRICE ROWS
-- on the same product, not separate products — mirrors the book exactly.
-- The empty license_product (0006) has no data/UI, so DROP + recreate is cleaner
-- than a column-by-column ALTER.
